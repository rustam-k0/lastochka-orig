<?php

/*
|--------------------------------------------------------------------------
| Dev-вход в админку по одноразовой ссылке
|--------------------------------------------------------------------------
|
| `php artisan dev:login-link <email>` печатает подписанную одноразовую
| ссылку. Переход по ней выпускает Sanctum-токен пользователя и кладёт его
| в JS-куку `admin_token`, которую читает admin_front, то есть браузер
| оказывается залогинен без пароля и 2FA.
|
| Два независимых гейта (см. App\Services\DevLoginService::isAvailable):
| 1) DEV_LOGIN_ENABLED=true;
| 2) хост из APP_URL входит в DEV_LOGIN_HOSTS (список через запятую).
| Привязка к хосту вместо проверки APP_ENV: на части dev-стендов стоит
| APP_ENV=production, а на части продов local, так что окружение ненадёжно.
| Скопированный на прод dev-.env не совпадёт по хосту и останется выключенным.
| Push в master деплоится и на dev, и на прод: на проде переменных в .env нет,
| роут не регистрируется, команда отказывает.
|
| Флаг читается через config(), не через env(): CI делает config:cache.
|
*/

return [
    'enabled' => (bool) env('DEV_LOGIN_ENABLED', false),

    // Хосты стендов, где dev-вход разрешён (через запятую), напр. `djami.comrades.dev`.
    // Должен совпадать с хостом APP_URL текущего стенда
    'hosts' => env('DEV_LOGIN_HOSTS', ''),

    // Время жизни ссылки в минутах (ссылка одноразовая независимо от TTL)
    'ttl_minutes' => (int) env('DEV_LOGIN_TTL_MINUTES', 5),

    // Имя Sanctum-токена; при повторном выпуске старые токены с этим именем удаляются
    'token_name' => 'dev-login',

    // Кука, из которой admin_front берёт Bearer-токен (см. src/stores/auth.js)
    'cookie' => 'admin_token',

    // Домен куки. null = host-only (фронт и API на одном хосте, как djami.comrades.dev).
    // Если фронт и API на разных поддоменах, указать родительский домен, напр. `.example.com`
    'cookie_domain' => env('DEV_LOGIN_COOKIE_DOMAIN'),

    // Куда редиректить после установки куки: путь или абсолютный URL фронта админки.
    // В роутере admin_front нет маршрута `/`, корень SPA это `/admin`
    'redirect' => env('DEV_LOGIN_REDIRECT', '/admin/'),
];
