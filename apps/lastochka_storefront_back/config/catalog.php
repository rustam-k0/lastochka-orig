    'category_tree' => [

        /*
         * Дефолт параметра `includeProducts`, когда клиент его не прислал.
         *
         * `includeProducts=1` добавляет в каждую конечную категорию до 8 товаров.
         * До 10.09.2026 они подгружались всегда при `includeChildren=1` и давали
         * 96 % веса ответа (на проде Ласточки 2 291 КБ из 2 376 КБ, 1 715 товаров
         * в 233 листьях), при том что мобильное приложение их не парсило:
         * замер 1,311 с / 2 376 КБ против 0,104 с / 85 КБ без них.
         *
         * Дефолт здесь `true` — старое поведение — намеренно: поле `products`
         * читают клиенты не всех форков. У Аладдина мобильное приложение рисует
         * `section.products[i]` в меню ресторана и отфильтровывает категории
         * условием `children.isNotEmpty || products.isNotEmpty`, поэтому лёгкий
         * ответ по умолчанию оставил бы экран магазина пустым. Форк, у которого
         * клиенты поле не читают, ставит `false` в своём `.env` и получает
         * лёгкий ответ, ничего не меняя в коде.
         *
         * Явный `includeProducts` в запросе всегда сильнее этого дефолта:
         * клиент может и включить товары при `false`, и отключить при `true`.
         */
        'include_products_default' => (bool) env('CATEGORY_TREE_INCLUDE_PRODUCTS_DEFAULT', true),
    ],

];
