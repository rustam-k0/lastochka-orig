<?php

/*
|--------------------------------------------------------------------------
| Dev-вход на клиентскую часть
|--------------------------------------------------------------------------
|
| Две команды на один и тот же механизм:
| 1) `php artisan dev:login-token <phone>` печатает Sanctum-токен пользователя,
|    то есть даёт войти в API как любой клиент без SMS-кода. Токен подставляется
|    в заголовок Authorization: Bearer (мобильное приложение, curl).
| 2) `php artisan dev:login-link <phone>` печатает одноразовую подписанную ссылку.
|    Переход по ней выпускает такой же токен и редиректит на веб-витрину (Nuxt)
|    с токеном во фрагменте URL (`#token=…`); витрина сама кладёт его в свою
|    куку `auth_token`, то есть браузер оказывается залогинен без SMS. Куку
|    ставит только витрина: вторая кука с тем же именем от API (на родительском
|    домене) ломала обычный вход по SMS, как только её токен протухал.
|    Ссылка нужна там, где у форка есть веб-фронт (mendev).
|
| Два независимых гейта: DEV_LOGIN_ENABLED=true и хост APP_URL входит в
| DEV_LOGIN_HOSTS (список через запятую). Привязка к хосту вместо APP_ENV:
| окружение на стендах ненадёжно, а скопированный на прод dev-.env не совпадёт
| по хосту и останется выключенным. Флаг читается через config(): config:cache.
|
*/

return [
    'enabled' => (bool) env('DEV_LOGIN_ENABLED', false),

    // Хосты стендов, где dev-вход разрешён (через запятую); должен совпадать с хостом APP_URL
    'hosts' => env('DEV_LOGIN_HOSTS', ''),

    // Время жизни ссылки в минутах (ссылка одноразовая независимо от TTL)
    'ttl_minutes' => (int) env('DEV_LOGIN_TTL_MINUTES', 5),

    // Имя Sanctum-токена; при повторном выпуске старые токены с этим именем удаляются
    'token_name' => 'dev-login',

    // Куда редиректить после выпуска токена: абсолютный URL веб-витрины, напр.
    // `https://raz-dev.mendev.ru/`. К нему дописывается фрагмент `#token=…`,
    // который витрина разбирает на клиенте (плагин dev-login-token, включается
    // NUXT_PUBLIC_DEV_LOGIN_ENABLED=true в .env витрины)
    'redirect' => env('DEV_LOGIN_REDIRECT', '/'),
];
