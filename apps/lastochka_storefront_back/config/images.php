<?php

declare(strict_types=1);

return [

    /*
    |--------------------------------------------------------------------------
    | Оптимизация изображений
    |--------------------------------------------------------------------------
    |
    | Витрина хранит производные копии картинок, оригиналы живут в admin_back
    | (поле source_url). Отдавать мобильному приложению исходники по 240–320 КБ
    | смысла нет: карточка в сетке рисуется в ~540 px, галерея товара — в 1170 px
    | на 3x-экране, зума в приложении нет.
    |
    | Замер на выборке 250 товарных фото прода (10.09.2026): 244 КБ → 73 КБ,
    | то есть −71 %. Три четверти каталога уже укладывается в max_width, для них
    | ресайза не происходит вообще — только перекодирование.
    |
    */

    'optimize' => [

        // Общий рубильник. Выключение не ломает ничего: картинки просто
        // сохраняются в исходном виде, как было до внедрения.
        'enabled' => (bool) env('IMAGE_OPTIMIZE_ENABLED', true),

        // Качество WebP. 85 выбрано осознанно: на худших сюжетах (мелкий текст
        // на упаковке, тёмный фон с градиентами) PSNR 34.9–43.4 дБ, разница
        // с оригиналом не видна при кропе 1:1. q80 даёт ещё ~5 % экономии,
        // но запас по качеству там заметно меньше.
        'quality' => (int) env('IMAGE_OPTIMIZE_QUALITY', 85),

        // Ограничение по ширине. Именно ограничение: картинки уже, чем
        // max_width, НЕ растягиваются — апскейл увеличивает файл и мылит.
        'max_width' => (int) env('IMAGE_OPTIMIZE_MAX_WIDTH', 1200),

        // Форматы-источники, которые имеет смысл перекодировать.
        // svg — вектор, gif — может быть анимированным, webp — уже целевой.
        'source_extensions' => ['jpg', 'jpeg', 'png', 'bmp'],

        // Таблицы и колонки, где лежат пути к картинкам. Используется командой
        // бэкфилла `images:optimize`. address_photos сюда намеренно не входит:
        // это пользовательские фото адресов доставки, не витринный контент.
        'backfill_targets' => [
            'product_images' => ['path'],
            'categories' => ['image_path'],
            'product_groups' => ['image_path'],
            'stories' => ['thumbnail_path'],
            'story_images' => ['path'],
            'announcements' => ['image_path'],
            'promotions' => ['image_path'],
            'banners' => ['image_path'],
            'stores' => ['image_path'],
            'product_group_filters' => ['image_path'],
        ],
    ],

    /*
    |--------------------------------------------------------------------------
    | Превью для сетки каталога
    |--------------------------------------------------------------------------
    |
    | Рядом с каждой картинкой витрины хранится уменьшенная копия
    | {папка}/thumbs/{имя}.webp. API отдаёт её в поле thumbPath, мобилка
    | рисует превью в карточках сетки, а полноразмерный path оставляет
    | для экрана товара. Если превью нет (svg, gif, картинка уже меньше,
    | ещё не прогнан бэкфилл), thumbPath совпадает с path.
    |
    | Ширину 300 px попросила мобильная команда: на слабой сети карточка
    | грузится за 10–20 КБ вместо 50–225 КБ.
    |
    */

    'thumbnails' => [

        'enabled' => (bool) env('IMAGE_THUMBNAILS_ENABLED', true),

        'width' => (int) env('IMAGE_THUMBNAILS_WIDTH', 300),

        // Для превью качество ниже, чем у полноразмерной копии: на 300 px
        // артефакты сжатия не видны, а вес падает заметно.
        'quality' => (int) env('IMAGE_THUMBNAILS_QUALITY', 80),

        // Имя каталога превью внутри папки исходной картинки.
        'directory' => 'thumbs',
    ],

];
