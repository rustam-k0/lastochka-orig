// Роуты карточек товара объявлены как /admin/product/:shop_id?/:id? — оба
// сегмента опциональные и позиционные. Если магазина нет (сетевой каталог,
// фильтр «Все магазины»), ссылка с params {shop_id: undefined, id: 123}
// схлопывается в /admin/product/123, и при переходе по прямой ссылке или F5
// роутер разбирает её обратно как {shop_id: 123, id: undefined} — открывается
// пустая форма создания вместо карточки товара.
//
// Поэтому вместо пропуска сегмента подставляем плейсхолдер «магазина нет».
// Значение 0 выбрано так, чтобы parseInt("0") === 0 был falsy: все чтения
// this.shop_id в карточках идут через `|| undefined` / проверку истинности,
// и отдельная обработка плейсхолдера не нужна.
export const NO_SHOP_ROUTE_PARAM = 0;
